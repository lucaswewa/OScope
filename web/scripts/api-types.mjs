// The API's types (ADR-0043): the server's own description of its API,
// `oscope-server --print-openapi`, made TypeScript by openapi-typescript, in
// src/api/generated/openapi.ts, which is committed.
//
//   npm run api:types    writes it again, after a change to the server
//   npm run api:check    fails when it is stale: when the server describes
//                        its API otherwise than the file says
//
// The server is OSCOPE_SERVER_BIN, or the workspace's debug build.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const web = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The committed file. */
export const FILE = join(web, "src", "api", "generated", "openapi.ts");

const HEADER = `// Generated by \`npm run api:types\` from \`oscope-server --print-openapi\`
// (ADR-0043). Don't edit it: \`npm run api:check\` fails when it is stale.

`;

/** The server's program: `OSCOPE_SERVER_BIN`, or the workspace's debug build. */
function program() {
  if (process.env.OSCOPE_SERVER_BIN) return process.env.OSCOPE_SERVER_BIN;
  const name = process.platform === "win32" ? "oscope-server.exe" : "oscope-server";
  const target = process.env.CARGO_TARGET_DIR ?? resolve(web, "..", "target");
  return join(target, "debug", name);
}

/**
 * The server's OpenAPI document.
 * @returns {object}
 */
export function described() {
  const server = program();
  const run = spawnSync(server, ["--print-openapi"], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (run.error) throw new Error(`can't run ${server}: ${run.error.message}`);
  if (run.status !== 0) {
    throw new Error(`${server} --print-openapi ended with ${run.status}: ${run.stderr}`);
  }
  return JSON.parse(run.stdout);
}

/**
 * A document's types, as the committed file holds them.
 * @param {object} document
 * @returns {Promise<string>}
 */
export async function typesOf(document) {
  const nodes = await openapiTS(/** @type {any} */ (document));
  return HEADER + astToString(nodes);
}

/**
 * The first line where two texts differ, line endings aside, or null.
 * @param {string} written
 * @param {string} wanted
 * @returns {{ line: number, written: string, wanted: string } | null}
 */
export function firstDifference(written, wanted) {
  const a = written.replace(/\r\n/g, "\n").split("\n");
  const b = wanted.replace(/\r\n/g, "\n").split("\n");
  for (let n = 0; n < Math.max(a.length, b.length); n++) {
    if (a[n] !== b[n]) {
      return { line: n + 1, written: a[n] ?? "(the end)", wanted: b[n] ?? "(the end)" };
    }
  }
  return null;
}

async function main() {
  const wanted = await typesOf(described());
  if (!process.argv.includes("--check")) {
    mkdirSync(dirname(FILE), { recursive: true });
    writeFileSync(FILE, wanted);
    console.log(`api:types: wrote ${FILE}`);
    return;
  }
  let written = "";
  try {
    written = readFileSync(FILE, "utf8");
  } catch {
    // None yet: as stale as can be.
  }
  const difference = firstDifference(written, wanted);
  if (difference) {
    console.error(
      `api:check: ${FILE} is stale, from its line ${difference.line}:\n` +
        `  the file:   ${difference.written}\n` +
        `  the server: ${difference.wanted}\n` +
        "Run `npm run api:types`, and commit what it writes.",
    );
    process.exit(1);
  }
  console.log("api:check: the API's types are the server's");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
