// The API's types (scripts/api-types.mjs, ADR-0043): made from the server's
// own description, and the check that fails when the committed file no
// longer matches it.
import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import { FILE, firstDifference, typesOf } from "../../scripts/api-types.mjs";

/** A description of one property, of a given type. */
const describing = (type: string) => ({
  openapi: "3.1.0",
  info: { title: "a server", version: "1" },
  paths: {
    "/api/v1/camera/gain": {
      get: {
        operationId: "gain",
        responses: {
          200: {
            description: "The gain.",
            content: { "application/json": { schema: { type } } },
          },
        },
      },
    },
  },
});

describe("the API's types", () => {
  it("are made from the server's description, and say so", async () => {
    const types = await typesOf(describing("number"));
    expect(types.startsWith("// Generated by `npm run api:types`")).toBe(true);
    expect(types).toContain('"/api/v1/camera/gain"');
    expect(types).toMatch(/"application\/json": number;/);
  });

  it("are stale when the description changes, from the line that differs", async () => {
    const before = await typesOf(describing("number"));
    const after = await typesOf(describing("string"));
    const difference = firstDifference(before, after);
    expect(difference).not.toBeNull();
    expect(difference!.written).toMatch(/number;$/);
    expect(difference!.wanted).toMatch(/string;$/);
    expect(before.split("\n")[difference!.line - 1]).toBe(difference!.written);
  });

  it("aren't stale when only their line endings differ", async () => {
    const types = await typesOf(describing("number"));
    expect(firstDifference(types, types)).toBeNull();
    expect(firstDifference(types.replace(/\n/g, "\r\n"), types)).toBeNull();
  });

  it("are stale when a line is missing at the end, or added", () => {
    expect(firstDifference("a\nb", "a\nb\nc")).toEqual({
      line: 3,
      written: "(the end)",
      wanted: "c",
    });
    expect(firstDifference("a\nb\nc", "a\nb")).toEqual({
      line: 3,
      written: "c",
      wanted: "(the end)",
    });
  });

  it("are committed, saying how they were made", () => {
    expect(readFileSync(FILE, "utf8").startsWith("// Generated by `npm run api:types`")).toBe(true);
  });
});
